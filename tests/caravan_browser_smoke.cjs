'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
const fs=require('node:fs');
(async()=>{
  fs.mkdirSync('caravan-smoke',{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:process.env.CARAVAN_CHROME_BIN,args:['--no-sandbox','--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:960,height:540},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.stack||String(e)));
  page.on('response',r=>{if(r.status()>=400 && r.url().includes('/game/assets/catalog/')) errors.push('Art asset missing '+r.status()+' '+r.url());});
  await page.goto('http://127.0.0.1:8787/web/',{waitUntil:'domcontentloaded'});
  await page.locator('#start').click();
  await page.waitForTimeout(350);
  assert.equal(await page.locator('#camera-mode').innerText(),'РОБОЧИЙ ОГЛЯД');
  await page.locator('[data-camera-mode="macro"]').click();
  await page.waitForTimeout(800);
  assert.equal(await page.locator('#camera-mode').innerText(),'ВЕСЬ ПОТЯГ');
  await page.screenshot({path:'caravan-smoke/01_macro_landscape.png'});
  await page.locator('[data-camera-mode="operational"]').click();
  await page.waitForTimeout(800);
  await page.mouse.click(370,353);
  await page.waitForTimeout(550);
  assert.equal(await page.locator('#panel').isVisible(),true,'Tapping a wagon must open context');
  assert.equal(await page.locator('#wagon-current').innerText().then(t=>t.startsWith('ВАГОН')),true);
  assert.equal(await page.locator('#camera-mode').innerText(),'ПОТОЧНИЙ ВАГОН');
  await page.screenshot({path:'caravan-smoke/02_wagon_focus.png'});
  await page.locator('#wagon-crew').click();
  assert.equal(await page.locator('#systems-panel').isVisible(),true);
  assert.equal(await page.locator('.crew-destination').count(),1,'Crew panel must link chosen wagon');
  await page.locator('[data-action="assignFocused"]').click();
  const snapshot=await page.evaluate(()=>window.CaravanGameplayQA.snapshot());
  assert.equal(snapshot.support.workers[0].job,1,'The chosen second wagon must receive worker job');
  await page.screenshot({path:'caravan-smoke/03_wagon_crew.png'});
  await page.locator('#systems-close').click();
  await page.locator('#cam-minus').click();
  await page.waitForTimeout(150);
  await page.locator('#cam-plus').click();
  await page.waitForTimeout(150);
  await page.locator('#cam-reset').click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('#camera-mode').innerText(),'РОБОЧИЙ ОГЛЯД');
  await page.screenshot({path:'caravan-smoke/04_operational_landscape.png'});
  assert.deepEqual(errors,[],'No JavaScript/page or missing art errors');
  await page.close();
  const desktop=await browser.newPage({viewport:{width:1440,height:810},deviceScaleFactor:1});
  desktop.on('pageerror',e=>errors.push(String(e)));
  await desktop.goto('http://127.0.0.1:8787/web/',{waitUntil:'domcontentloaded'});
  await desktop.locator('#start').click();
  await desktop.waitForTimeout(350);
  await desktop.screenshot({path:'caravan-smoke/05_desktop_overview.png'});
  assert.deepEqual(errors,[],'No runtime errors on desktop');
  await browser.close();
  console.log('PASS: camera modes, select-wagon, crew destination, zoom controls, Android-landscape and desktop screenshots');
})().catch(e=>{console.error(e);process.exitCode=1;});
